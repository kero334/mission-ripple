import {chromium} from 'playwright';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
const root=resolve('.');
const packageRoot=resolve('../NASA-Science-to-Mission-Engine/MISSION_RIPPLE_COMPLETE_SCIENTIFIC_DATA');
const evidence=JSON.parse(readFileSync('src/science/evidence-v1.json','utf8'));
const raw=readFileSync(resolve(packageRoot,evidence.sourceRecord));
const checks=[],errors=[];
const check=(name,pass,detail='')=>checks.push({name,pass,detail});
check('Source hash matches immutable snapshot',createHash('sha256').update(raw).digest('hex')===evidence.sourceSha256);
const csv=raw.toString('utf8').trim().split(/\r?\n/),records=new Map(csv.slice(1).map(line=>{const parts=line.replaceAll('"','').split(',');return [parts[0],parts]}));
check('All chart rows match original NASA CSV',evidence.measurements.every(p=>{const r=records.get(p.recordSelector.timestamp);return r?.[1]==='MSL-RAD-Surface'&&Number(r?.[2])===p.absorbedDoseRate&&r?.[3]===''}));
check('Observed units and limits retained',evidence.measurements.every(p=>p.unit==='µGy/hour')&&evidence.derived.peak===303.98798&&evidence.derived.readingsAboveExploratoryCutoff===92&&evidence.uncertainty.en.includes('No astronaut'));
check('Provenance references present',evidence.findingIds.every(id=>evidence.provenanceRefs.includes(id))&&evidence.sourceUrl.includes('nasa.gov'));
mkdirSync('qa-screenshots/science',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1280,height:720}});
const page=await context.newPage();
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://localhost:5182/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>Boolean(window.__ripple?.scene?.player&&window.__mission));
check('Game launches',await page.locator('#mission-title').isVisible());
const rejects=await page.evaluate(()=>{const api=window.__mission,e=api.getEvidence();const missing=structuredClone(e),unsafe=structuredClone(e);missing.provenanceRefs=[];unsafe.habitatDose=12;let a=false,b=false;try{api.validateEvidenceRecord(missing)}catch{a=true}try{api.validateEvidenceRecord(unsafe)}catch{b=true}return {a,b}});
check('Missing provenance rejected',rejects.a);
check('Unsupported habitat-dose claim rejected',rejects.b);
await page.locator('#science-mission-button').click();
check('Mission starts and briefing appears',(await page.evaluate(()=>window.__mission.getState().stage))==='monitor'&&await page.locator('#science-overlay').isVisible());
await page.screenshot({path:'qa-screenshots/science/01-briefing.png'});
await page.locator('[data-science-action="close"]').click();
await page.keyboard.down('s');
await page.waitForFunction(()=>window.__ripple.state().nearest==='Inspect field terminal',null,{timeout:5000});
await page.keyboard.up('s');
const pos=await page.evaluate(()=>window.__ripple.state());
check('Player walks to field terminal',pos.position.y>650&&pos.nearest==='Inspect field terminal',JSON.stringify(pos.position));
await page.keyboard.press('e');await page.locator('.learning-source').waitFor();
check('Field interaction opens child-facing rover reading',await page.locator('#science-content').getByText('One reading reached about 304 µGy/hour.').isVisible());
check('Exact NASA value remains in optional source',await page.locator('#science-content').getByText('303.98798 µGy/hour',{exact:false}).count()>0);
check('Source details start collapsed',await page.locator('.learning-source').evaluate(el=>!el.open));
await page.screenshot({path:'qa-screenshots/science/02-field-evidence.png'});
await page.locator('[data-science-action="monitor-reviewed"]').click();
check('Objective advances to Research',await page.evaluate(()=>window.__mission.getState().stage==='research'));
await page.evaluate(()=>window.__ripple.travel('research'));
await page.waitForFunction(()=>window.__ripple.state().room==='research');
await page.waitForTimeout(250);
await page.keyboard.press('e');
check('Research equipment opens evidence and uncertainty',await page.locator('#science-content').getByText("WHAT WE DON'T KNOW").isVisible());
await page.screenshot({path:'qa-screenshots/science/03-research-evidence.png'});
await page.locator('[data-science-action="research-reviewed"]').click();
await page.evaluate(()=>window.__ripple.travel('command'));
await page.waitForFunction(()=>window.__ripple.state().room==='command');
await page.waitForTimeout(240);await page.keyboard.press('e');
check('Command offers two illustrated scheduling cards',await page.locator('[data-science-action="review-defer"]').isVisible()&&await page.locator('[data-science-action="survey-followup"]').isVisible()&&await page.locator('.learning-option img').count()===2);
await page.screenshot({path:'qa-screenshots/science/04-decision.png'});
await page.locator('[data-science-action="review-defer"]').click();
check('Choice A immediate simulated consequence',await page.evaluate(()=>window.__mission.getState().choice==='review-defer'&&window.__mission.getState().nextShiftFlag==='trend_reviewed'));
await page.screenshot({path:'qa-screenshots/science/05-immediate.png'});
await page.reload({waitUntil:'networkidle'});await page.waitForFunction(()=>Boolean(window.__mission&&window.__ripple?.scene?.player));
check('Choice and delayed flag survive reload',await page.evaluate(()=>window.__mission.getState().stage==='nextShift'&&window.__mission.getState().nextShiftFlag==='trend_reviewed'));
await page.evaluate(()=>window.__ripple.travel('comms'));
await page.waitForFunction(()=>window.__ripple.state().room==='comms');
await page.waitForTimeout(240);await page.keyboard.press('e');
check('Communications shows delayed consequence',await page.locator('#science-content').getByText('optional robot survey is still pending').isVisible());
await page.screenshot({path:'qa-screenshots/science/06-delayed.png'});
await page.locator('[data-science-action="next-shift-reviewed"]').click();
check('Science debrief visible',await page.locator('#science-content').getByText('Science debrief').isVisible());
await page.screenshot({path:'qa-screenshots/science/07-debrief.png'});
await page.locator('[data-science-action="finish"]').click();
check('Mission completes',await page.evaluate(()=>window.__mission.getState().stage==='complete'));
await page.locator('#science-close').click();
await page.keyboard.press('l');
check('Arabic mission HUD and RTL',await page.locator('html').getAttribute('dir')==='rtl'&&await page.locator('#mission-title').textContent()==='قراءة عربة المريخ');
await page.locator('#science-mission-button').click();await page.screenshot({path:'qa-screenshots/science/08-arabic.png'});
await page.locator('#science-close').click();
await page.evaluate(()=>window.__mission.replay());
await page.locator('#science-mission-button').click();await page.locator('[data-science-action="close"]').click();
await page.evaluate(()=>window.dispatchEvent(new CustomEvent('ripple-world-interaction',{detail:{kind:'field',buildingId:null}})));
await page.locator('[data-science-action="monitor-reviewed"]').click();
await page.evaluate(()=>window.dispatchEvent(new CustomEvent('ripple-world-interaction',{detail:{kind:'equipment',buildingId:'research'}})));
await page.locator('[data-science-action="research-reviewed"]').click();
await page.evaluate(()=>window.dispatchEvent(new CustomEvent('ripple-world-interaction',{detail:{kind:'equipment',buildingId:'command'}})));
await page.locator('[data-science-action="survey-followup"]').click();
check('Choice B distinct delayed flag',await page.evaluate(()=>window.__mission.getState().choice==='survey-followup'&&window.__mission.getState().nextShiftFlag==='followup_reading_due'));
check('No browser errors',errors.length===0,errors.join('; '));
const report={checks,errors};writeFileSync('qa-screenshots/science/results.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
await browser.close();
