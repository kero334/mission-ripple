import { chromium } from 'playwright';
import { mkdirSync,writeFileSync } from 'node:fs';
const out='qa-screenshots';mkdirSync(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://localhost:5182/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>Boolean(window.__ripple?.scene?.player?.texture));
await page.screenshot({path:`${out}/01-arrival.png`});
await page.getByText('BEGIN EXPLORING').click();
await page.keyboard.down('d');await page.waitForTimeout(500);await page.keyboard.up('d');
const moved=await page.evaluate(()=>window.__ripple.state().position);
await page.screenshot({path:`${out}/02-exterior.png`});
await page.setViewportSize({width:1280,height:720});await page.waitForTimeout(180);await page.screenshot({path:`${out}/02-exterior-laptop.png`});
await page.setViewportSize({width:1600,height:900});
await page.evaluate(()=>{const s=window.__ripple.scene;s.player.setPosition(1270,500)});
await page.waitForTimeout(180);await page.keyboard.press('e');
await page.waitForTimeout(700);
const room=await page.evaluate(()=>window.__ripple.state());
await page.screenshot({path:`${out}/03-command-interior.png`});
await page.evaluate(()=>{const s=window.__ripple.scene;s.player.setPosition(720,590)});
await page.waitForTimeout(180);await page.keyboard.press('e');
await page.waitForTimeout(200);
const inspection=await page.locator('#nuri-text').textContent();
await page.getByRole('button',{name:'Language'}).click();
await page.screenshot({path:`${out}/04-arabic-interior.png`});
await page.evaluate(()=>{const s=window.__ripple.scene;s.player.setPosition(720,855)});
await page.waitForTimeout(180);await page.keyboard.press('e');await page.waitForTimeout(700);
const exited=await page.evaluate(()=>window.__ripple.state());
await page.keyboard.press('m');await page.waitForTimeout(100);const mapVisible=await page.locator('#map-panel').isVisible();
await page.screenshot({path:`${out}/05-map.png`});
await page.keyboard.press('m');
const buildings=[['habitat',680,650],['power',1670,690],['greenhouse',2130,1000],['water',1640,1350],['comms',850,1350],['shelter',305,1050],['oxygen',1270,1010]];
const visited=[];
for(const [id,x,y] of buildings){
  await page.evaluate(([px,py])=>{window.__ripple.scene.player.setPosition(px,py)},[x,y+35]);
  await page.waitForTimeout(130);await page.keyboard.press('e');await page.waitForTimeout(610);
  const current=await page.evaluate(()=>window.__ripple.state().room);visited.push([id,current]);
  if(id==='greenhouse'||id==='water')await page.screenshot({path:`${out}/06-${id}-interior.png`});
  await page.evaluate(()=>window.__ripple.scene.player.setPosition(720,855));
  await page.waitForTimeout(130);await page.keyboard.press('e');await page.waitForTimeout(610);
}
await page.setViewportSize({width:2600,height:1800});await page.waitForTimeout(350);
await page.screenshot({path:`${out}/07-world-overview.png`,animations:'disabled'});
const results={moved,room,inspection,exited,mapVisible,visited,final:await page.evaluate(()=>window.__ripple.state()),errors};
writeFileSync(`${out}/playtest-results.json`,JSON.stringify(results,null,2));
console.log(JSON.stringify(results));
await browser.close();
